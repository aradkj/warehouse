"""Initial Phase 1 schema for every implemented bounded context.

Revision ID: 0001_initial_schema
Revises: -

This revision creates the complete Phase 1 schema:

* **identity**  - ``tenants``
* **catalog**   - ``products``, ``skus``
* **inventory** - ``warehouses``, ``inventory_items``, ``inventory_movements``,
  ``reservations``, ``reservation_allocations``
* **ordering**  - ``orders``, ``order_lines``
* **platform**  - ``idempotency_records``

Three properties of this migration matter operationally:

1. **Referential order.** Tables are created parents-first and dropped
   children-first, so a rollback never hits a foreign key violation.
2. **Invariants live in the database too.** The headline rules
   (``available >= 0``, one ACTIVE reservation per order, non-negative prices,
   valid lifecycle states) are ``CHECK`` constraints and partial unique indexes.
   Application code is the first line of defence; PostgreSQL is the last.
3. **Tenant ownership is structural.** Every business table except ``tenants``
   carries ``tenant_id NOT NULL`` with a ``RESTRICT`` foreign key, and every
   tenant-scoped index is prefixed by it.

The DDL was generated by Alembic autogenerate and then reviewed: it is
guaranteed to match ``shared.infrastructure.db.registry`` metadata, which the
migration drift test asserts on every test run
(``tests/integration/test_migration_drift.py``).

Downgrade drops everything this revision created (``alembic downgrade base``).
It is safe on an empty or test database and destroys data by design; production
rollbacks follow ``docs/runbooks/migrations.md``.
"""

