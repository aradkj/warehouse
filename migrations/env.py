"""Alembic environment.

Design decisions:

* **The database URL comes from the application settings** (``ARAD_DATABASE_URL``),
  never from a checked-in value, so a migration always targets the same database
  the application talks to.
* **``compare_type=True`` and ``compare_server_default=True``** so an
  autogenerated migration cannot silently miss a column type or default change.
* **All metadata is imported** through ``shared.infrastructure.db.registry``,
  which is the single place that knows about every table definition.
* **``render_as_batch`` is off**: PostgreSQL supports transactional DDL, so a
  failed migration rolls back cleanly instead of leaving a half-applied schema.
"""

from __future__ import annotations

import asyncio
import os
from logging.config import fileConfig

from alembic import context
from sqlalchemy import pool
from sqlalchemy.engine import Connection
from sqlalchemy.ext.asyncio import async_engine_from_config

import shared.infrastructure.db.registry  # noqa: F401  (registers every table)
from shared.infrastructure.db.base import metadata

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

target_metadata = metadata


def _database_url() -> str:
    """Resolve the migration target URL."""
    override = context.get_x_argument(as_dictionary=True).get("db-url")
    if override:
        return str(override)
    from_env = os.environ.get("ARAD_DATABASE_URL")
    if from_env:
        return from_env
    from bootstrap.config import get_settings

    return get_settings().database_url


def run_migrations_offline() -> None:
    """Emit SQL to stdout (``alembic upgrade head --sql``)."""
    context.configure(
        url=_database_url(),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        compare_type=True,
        compare_server_default=True,
        include_schemas=False,
    )
    with context.begin_transaction():
        context.run_migrations()


def _do_run_migrations(connection: Connection) -> None:
    context.configure(
        connection=connection,
        target_metadata=target_metadata,
        compare_type=True,
        compare_server_default=True,
        # Keep autogenerate diffs deterministic and reviewable.
        include_schemas=False,
    )
    with context.begin_transaction():
        context.run_migrations()


async def run_migrations_online() -> None:
    """Apply migrations against a live database (async engine)."""
    configuration = config.get_section(config.config_ini_section) or {}
    configuration["sqlalchemy.url"] = _database_url()
    connectable = async_engine_from_config(
        configuration,
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
        future=True,
    )
    async with connectable.connect() as connection:
        await connection.run_sync(_do_run_migrations)
    await connectable.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    asyncio.run(run_migrations_online())
